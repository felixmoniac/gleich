        var stelle = d.integer(forKey: "zen.stelle")
        if reihe.count != sprueche.count || stelle >= reihe.count {
            // Neue Runde, frisch gemischt – aber nicht mit dem zuletzt gezeigten beginnen.
            let letzter = reihe.indices.contains(stelle - 1) ? reihe[stelle - 1] : -1
            reihe = Array(sprueche.indices).shuffled()
            if reihe.first == letzter { reihe.swapAt(0, reihe.count - 1) }
            stelle = 0
        }
        let text = sprueche[reihe[stelle]]
        d.set(reihe, forKey: "zen.reihe")
        d.set(stelle + 1, forKey: "zen.stelle")
        return text
    }

